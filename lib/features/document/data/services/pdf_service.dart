import 'dart:io';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

/// Generates PDF files from extracted document text or AI summaries.
///
/// Each PDF uses A4 format, proper margins, and [pw.MultiPage] so
/// long documents are automatically split across multiple pages.
class PdfService {
  // ─── Public API ───────────────────────────────────────────────────

  /// Generates a PDF of the OCR-extracted text and saves it to [outputPath].
  Future<File> generateOriginalTextPdf({
    required String text,
    required String documentTitle,
    required DateTime captureDate,
    required String outputPath,
  }) {
    return _generate(
      sectionTitle: 'EXTRACTED TEXT',
      content: text,
      documentTitle: documentTitle,
      captureDate: captureDate,
      outputPath: outputPath,
    );
  }

  /// Generates a PDF of the AI-generated summary and saves it to [outputPath].
  Future<File> generateSummaryPdf({
    required String text,
    required String documentTitle,
    required DateTime captureDate,
    required String outputPath,
  }) {
    return _generate(
      sectionTitle: 'AI GENERATED SUMMARY',
      content: text,
      documentTitle: documentTitle,
      captureDate: captureDate,
      outputPath: outputPath,
    );
  }

  // ─── Internal ─────────────────────────────────────────────────────

  Future<File> _generate({
    required String sectionTitle,
    required String content,
    required String documentTitle,
    required DateTime captureDate,
    required String outputPath,
  }) async {
    final pdf = pw.Document(
      title: 'Naadh',
      author: 'Naadh',
      creator: 'Alien Innovations',
    );

    final dateStr = _formatDate(captureDate);

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.symmetric(horizontal: 48, vertical: 40),
        // Page numbers only exist while a page is being laid out, so they
        // belong in the footer. Reading them in `build` threw "Null check
        // operator used on a null value" on every save.
        footer: (pw.Context context) => pw.Align(
          alignment: pw.Alignment.centerRight,
          child: pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
          ),
        ),
        build: (pw.Context context) => [
          // ── App title ──────────────────────────────────────────────
          pw.Text(
            'Naadh',
            style: pw.TextStyle(
              fontSize: 22,
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.deepPurple800,
            ),
          ),
          pw.SizedBox(height: 6),

          // ── Document metadata ──────────────────────────────────────
          pw.Text(
            'Document: $documentTitle',
            style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700),
          ),
          pw.Text(
            'Captured: $dateStr',
            style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700),
          ),
          pw.SizedBox(height: 6),
          pw.Divider(color: PdfColors.deepPurple200, thickness: 1.5),
          pw.SizedBox(height: 8),

          // ── Section heading ────────────────────────────────────────
          pw.Text(
            sectionTitle,
            style: pw.TextStyle(
              fontSize: 15,
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.deepPurple600,
            ),
          ),
          pw.SizedBox(height: 12),

          // ── Main content ───────────────────────────────────────────
          // One widget per line so long documents flow onto more pages
          // (a single Text taller than a page cannot be split).
          for (final line in _pageableLines(
            content.isEmpty ? '(No content available)' : content,
          ))
            pw.Text(
              line,
              style: const pw.TextStyle(fontSize: 12),
              textAlign: pw.TextAlign.left,
            ),
          pw.SizedBox(height: 24),

          // ── Footer ─────────────────────────────────────────────────
          pw.Divider(color: PdfColors.grey300),
          pw.Text(
            'Generated by Naadh — Alien Innovations',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
            textAlign: pw.TextAlign.center,
          ),
        ],
      ),
    );

    final bytes = await pdf.save();
    final file = File(outputPath);
    await file.parent.create(recursive: true);
    await file.writeAsBytes(bytes);
    return file;
  }

  /// Lines of [text], with very long lines cut at word boundaries so no
  /// single line can be taller than a page.
  static List<String> _pageableLines(String text, {int maxChars = 1500}) {
    final out = <String>[];
    for (final line in text.split('\n')) {
      var rest = line;
      while (rest.length > maxChars) {
        var cut = rest.lastIndexOf(' ', maxChars);
        if (cut <= 0) cut = maxChars;
        out.add(rest.substring(0, cut));
        rest = rest.substring(cut).trimLeft();
      }
      out.add(rest.isEmpty ? ' ' : rest);
    }
    return out;
  }

  // ─── Date formatting (no intl dependency) ────────────────────────

  static const _months = [
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];

  String _formatDate(DateTime dt) {
    final h = dt.hour.toString().padLeft(2, '0');
    final m = dt.minute.toString().padLeft(2, '0');
    return '${dt.day} ${_months[dt.month - 1]} ${dt.year}, $h:$m';
  }
}
